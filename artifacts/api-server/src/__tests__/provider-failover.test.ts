// ─── SSRF protection — runtime callLlm() ─────────────────────────────────────

describe("ProviderRegistry — SSRF protection at runtime", () => {
  const LOOPBACK_PROVIDER_ID = `fo-ssrf-${randomUUID()}`;
  const BOT_SSRF = `fo-ssrf-bot-${randomUUID()}`;

  beforeAll(async () => {
    // Store a provider whose baseUrl points at the loopback address.
    // In a real attack this would be inserted directly into the DB after
    // bypassing the create route (e.g., in a race between DNS validation and
    // use). The registry must reject it at call time regardless.
    await db.insert(providersTable).values({
      id: LOOPBACK_PROVIDER_ID,
      tenantId: T_ID,
      kind: "LLM",
      vendor: "openai-compatible",
      displayName: "SSRF Loopback Provider",
      baseUrl: "http://127.0.0.1:8080", // loopback — must be blocked
      authMode: "bearer",
      apiKeyEncrypted: encryptKey("ssrf-test-key"),
      enabled: true,
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });

    await db.insert(botsTable).values({
      id: BOT_SSRF,
      displayName: "SSRF Test Bot",
      sipExtension: "FO-SSRF",
      status: "OFFLINE",
      activeCalls: 0,
      tenantId: T_ID,
      supportedLanguages: ["en"],
      defaultGreetingLanguage: "en",
      timezone: "UTC",
      endpointSilenceMs: 1200,
      backchannelThresholdMs: 700,
      silenceRecoverySecs: 6,
      direction: "inbound",
      llmChainJson: [{ provider_id: LOOPBACK_PROVIDER_ID, model_id: "custom-model" }],
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });
  });

  afterAll(async () => {
    await db.delete(botsTable).where(eq(botsTable.id, BOT_SSRF)).catch(() => {});
    await db.delete(providersTable).where(eq(providersTable.id, LOOPBACK_PROVIDER_ID)).catch(() => {});
  });

  it("rejects a private/loopback baseUrl at runtime before making an outbound call", async () => {
    const registry = new ProviderRegistry();
    const fetchSpy = vi.spyOn(global, "fetch"); // must NOT be called

    await expect(
      registry.callLlm({
        systemPrompt: "Test.",
        userPrompt: "Test.",
        tenantId: T_ID,
        botId: BOT_SSRF,
      })
    ).rejects.toThrow();

    // fetch must not have been called with the loopback URL
    const loopbackCalls = fetchSpy.mock.calls.filter((args) =>
      String(args[0]).includes("127.0.0.1")
    );
    expect(loopbackCalls).toHaveLength(0);
  });
});


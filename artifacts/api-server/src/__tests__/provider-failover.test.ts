// ─── Cross-tenant provider isolation ─────────────────────────────────────────

describe("ProviderRegistry — cross-tenant isolation", () => {
  const T_OTHER = `fo-other-${randomUUID()}`;
  const P_OTHER = `fo-other-p-${randomUUID()}`;
  const BOT_CROSS = `fo-cross-bot-${randomUUID()}`;

  beforeAll(async () => {
    // Seed a second tenant with its own LLM provider
    await db.insert(tenantsTable).values({
      id: T_OTHER,
      name: "Other Tenant",
      slug: `other-${T_OTHER.slice(-6)}`,
      status: "active",
      region: "global",
      webhookSecret: `other-secret-${randomUUID()}`,
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });

    await db.insert(providersTable).values({
      id: P_OTHER,
      tenantId: T_OTHER,
      kind: "LLM",
      vendor: "openai",
      displayName: "Other Tenant's Provider",
      authMode: "bearer",
      apiKeyEncrypted: encryptKey("other-tenant-secret-key"),
      enabled: true,
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });

    // Bot belonging to T_ID whose llmChainJson references T_OTHER's provider
    await db.insert(botsTable).values({
      id: BOT_CROSS,
      displayName: "Cross-Tenant Attack Bot",
      sipExtension: "FO-CROSS",
      status: "OFFLINE",
      activeCalls: 0,
      tenantId: T_ID,
      supportedLanguages: ["en"],
      defaultGreetingLanguage: "en",
      timezone: "UTC",
      endpointSilenceMs: 1200,
      backchannelThresholdMs: 700,
      silenceRecoverySecs: 6,
      direction: "inbound",
      // Attempt to reference a provider from T_OTHER (cross-tenant attack)
      llmChainJson: [
        { provider_id: P_OTHER, model_id: "gpt-4o" },
      ],
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });
  });

  afterAll(async () => {
    await db.delete(botsTable).where(eq(botsTable.id, BOT_CROSS)).catch(() => {});
    await db.delete(providersTable).where(eq(providersTable.id, P_OTHER)).catch(() => {});
    await db.delete(tenantsTable).where(eq(tenantsTable.id, T_OTHER)).catch(() => {});
  });

  it("cannot use another tenant's provider via explicit bot chain", async () => {
    const registry = new ProviderRegistry();

    // The chain references P_OTHER which belongs to T_OTHER, not T_ID.
    // buildLlmChain must silently drop it (cross-tenant scope rejection).
    // With no valid entries, it falls back to the env-var legacy chain.
    // Since no OPENAI_API_KEY etc. are set in the test environment, the
    // returned chain should be empty OR skip directly to env-var fallback.
    const chain = await registry.buildLlmChain(T_ID, BOT_CROSS);

    // P_OTHER must NOT appear in the resolved chain under any circumstances
    const providerIds = chain.map((e) => e.provider.id);
    expect(providerIds).not.toContain(P_OTHER);
  });

  it("resolveStt rejects a foreign tenant's STT provider", async () => {
    // Seed a foreign STT provider
    const P_FOREIGN_STT = `fo-fstt-${randomUUID()}`;
    await db.insert(providersTable).values({
      id: P_FOREIGN_STT,
      tenantId: T_OTHER,
      kind: "STT",
      vendor: "deepgram",
      displayName: "Foreign STT",
      authMode: "bearer",
      apiKeyEncrypted: encryptKey("foreign-stt-key"),
      enabled: true,
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });

    // Bot in T_ID referencing foreign STT
    const BOT_STT = `fo-bstt-${randomUUID()}`;
    await db.insert(botsTable).values({
      id: BOT_STT,
      displayName: "STT Cross-Tenant Bot",
      sipExtension: "FO-STT",
      status: "OFFLINE",
      activeCalls: 0,
      tenantId: T_ID,
      supportedLanguages: ["en"],
      defaultGreetingLanguage: "en",
      timezone: "UTC",
      endpointSilenceMs: 1200,
      backchannelThresholdMs: 700,
      silenceRecoverySecs: 6,
      direction: "inbound",
      sttMapJson: { en: { provider_id: P_FOREIGN_STT, model_id: "nova-2" } },
    }).onDuplicateKeyUpdate({ set: { id: sql`id` } });

    const registry = new ProviderRegistry();
    const result = await registry.resolveStt(T_ID, "en", BOT_STT);

    // The foreign provider must be rejected → result falls through to tenant-level
    // STT providers (none configured for T_ID) → null
    expect(result).toBeNull();

    await db.delete(botsTable).where(eq(botsTable.id, BOT_STT)).catch(() => {});
    await db.delete(providersTable).where(eq(providersTable.id, P_FOREIGN_STT)).catch(() => {});
  });
});

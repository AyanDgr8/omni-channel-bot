describe("isPrivateIp — NAT64 (64:ff9b::/96) checks", () => {
  it("blocks NAT64 dotted-decimal private embedded IPv4 (64:ff9b::192.168.1.1)", async () => {
    const { isPrivateIp } = await import("../lib/ssrf-guard.js");
    expect(isPrivateIp("64:ff9b::192.168.1.1")).toBe(true);
    expect(isPrivateIp("64:ff9b::10.0.0.1")).toBe(true);
    expect(isPrivateIp("64:ff9b::127.0.0.1")).toBe(true);
  });

  it("blocks NAT64 hex-group private embedded IPv4 (64:ff9b::c0a8:0101 = 192.168.1.1)", async () => {
    const { isPrivateIp } = await import("../lib/ssrf-guard.js");
    // 192.168.1.1 → c0a8:0101
    expect(isPrivateIp("64:ff9b::c0a8:0101")).toBe(true);
    // 10.0.0.1 → 0a00:0001
    expect(isPrivateIp("64:ff9b::0a00:0001")).toBe(true);
    // 127.0.0.1 → 7f00:0001
    expect(isPrivateIp("64:ff9b::7f00:0001")).toBe(true);
    // 169.254.169.254 (cloud metadata) → a9fe:a9fe
    expect(isPrivateIp("64:ff9b::a9fe:a9fe")).toBe(true);
  });

  it("does not block NAT64 with public embedded IPv4 (64:ff9b::8.8.8.8 = Google DNS)", async () => {
    const { isPrivateIp } = await import("../lib/ssrf-guard.js");
    expect(isPrivateIp("64:ff9b::8.8.8.8")).toBe(false);
    // 8.8.8.8 → 0808:0808
    expect(isPrivateIp("64:ff9b::0808:0808")).toBe(false);
  });
});


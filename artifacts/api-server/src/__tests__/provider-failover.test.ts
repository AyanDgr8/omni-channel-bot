// ─── Helpers ─────────────────────────────────────────────────────────────────

function makeOpenAISuccessResponse(): Response {
  return new Response(
    JSON.stringify({
      choices: [{ message: { content: "Hello from OpenAI" } }],
      usage: { prompt_tokens: 10, completion_tokens: 5 },
    }),
    { status: 200, headers: { "Content-Type": "application/json" } }
  );
}

function makeAnthropicSuccessResponse(): Response {
  return new Response(
    JSON.stringify({
      content: [{ text: "Hello from Anthropic" }],
      usage: { input_tokens: 10, output_tokens: 5 },
    }),
    { status: 200, headers: { "Content-Type": "application/json" } }
  );
}

function make500Response(): Response {
  return new Response(JSON.stringify({ error: { message: "Internal Server Error" } }), {
    status: 500,
    headers: { "Content-Type": "application/json" },
  });
}

// ─── Tests ────────────────────────────────────────────────────────────────────

describe("ProviderRegistry.callLlm — failover chain", () => {
  it("returns the first provider's response when it succeeds", async () => {
    const registry = new ProviderRegistry();
    vi.spyOn(global, "fetch").mockResolvedValueOnce(makeOpenAISuccessResponse());

    const result = await registry.callLlm({
      systemPrompt: "You are a test bot.",
      userPrompt: "Say hello.",
      tenantId: T_ID,
      botId: BOT_ID,
    });

    expect(result.text).toBe("Hello from OpenAI");
    expect(result.vendor).toBe("openai");
    expect(result.providerId).toBe(P1_ID);
  });

  it("falls over to provider 2 when provider 1 returns HTTP 500", async () => {
    const registry = new ProviderRegistry();

    // First call → OpenAI 500; second call → Anthropic 200
    vi.spyOn(global, "fetch")
      .mockResolvedValueOnce(make500Response())
      .mockResolvedValueOnce(makeAnthropicSuccessResponse());

    const result = await registry.callLlm({
      systemPrompt: "You are a test bot.",
      userPrompt: "Say hello.",
      tenantId: T_ID,
      botId: BOT_ID,
    });

    expect(result.text).toBe("Hello from Anthropic");
    expect(result.vendor).toBe("anthropic");
    expect(result.providerId).toBe(P2_ID);
  });

  it("writes provider_call_log rows for each attempt", async () => {
    const registry = new ProviderRegistry();

    // Provider 1 fails, provider 2 succeeds
    vi.spyOn(global, "fetch")
      .mockResolvedValueOnce(make500Response())
      .mockResolvedValueOnce(makeAnthropicSuccessResponse());

    await registry.callLlm({
      systemPrompt: "Log test.",
      userPrompt: "Test.",
      tenantId: T_ID,
      botId: BOT_ID,
    });

    // Allow async log insert to settle
    await new Promise((r) => setTimeout(r, 200));

    const logs = await db
      .select()
      .from(providerCallLogTable)
      .where(and(eq(providerCallLogTable.tenantId, T_ID), eq(providerCallLogTable.providerKind, "LLM")));

    // Should have at least 2 log rows: one error (openai) + one success (anthropic)
    const errorLog = logs.find((l) => l.outcomeStatus === "error" && l.providerVendor === "openai");
    const successLog = logs.find((l) => l.outcomeStatus === "success" && l.providerVendor === "anthropic");

    expect(errorLog).toBeDefined();
    expect(errorLog?.providerId).toBe(P1_ID);
    expect(successLog).toBeDefined();
    expect(successLog?.providerId).toBe(P2_ID);
  });

  it("throws when all providers in the chain fail", async () => {
    const registry = new ProviderRegistry();

    vi.spyOn(global, "fetch")
      .mockResolvedValueOnce(make500Response())  // openai fails
      .mockResolvedValueOnce(make500Response());  // anthropic also fails

    await expect(
      registry.callLlm({
        systemPrompt: "All fail test.",
        userPrompt: "Test.",
        tenantId: T_ID,
        botId: BOT_ID,
      })
    ).rejects.toThrow("All LLM providers exhausted");
  });

  it("opens the circuit breaker after repeated failures and skips the provider", async () => {
    const registry = new ProviderRegistry();

    // Trip provider 1's breaker past the threshold (5 failures)
    for (let i = 0; i < 5; i++) {
      vi.spyOn(global, "fetch")
        .mockResolvedValueOnce(make500Response())  // p1 fails
        .mockResolvedValueOnce(makeAnthropicSuccessResponse()); // p2 succeeds
      await registry.callLlm({
        systemPrompt: "Breaker test.",
        userPrompt: `Trip ${i}.`,
        tenantId: T_ID,
        botId: BOT_ID,
      });
      vi.restoreAllMocks();
    }

    // Now provider 1's breaker should be open — only ONE fetch (provider 2)
    const fetchSpy = vi.spyOn(global, "fetch")
      .mockResolvedValueOnce(makeAnthropicSuccessResponse());

    const result = await registry.callLlm({
      systemPrompt: "Breaker open test.",
      userPrompt: "Should skip p1.",
      tenantId: T_ID,
      botId: BOT_ID,
    });

    expect(result.vendor).toBe("anthropic");
    // fetch should only have been called once (provider 2 only)
    expect(fetchSpy).toHaveBeenCalledTimes(1);
  });
});

